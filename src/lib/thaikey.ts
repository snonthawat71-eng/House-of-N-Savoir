/** แป้นพิมพ์ไทยเกษมณี: ตัวอักษรอังกฤษที่กด → ตัวอักษรไทยที่ออกมา */
const TH_FROM_EN: Record<string, string> = {
  "1": "ๅ", "2": "/", "3": "-", "4": "ภ", "5": "ถ", "6": "ุ", "7": "ึ", "8": "ค", "9": "ต", "0": "จ",
  "-": "ข", "=": "ช", "`": "_",
  q: "ๆ", w: "ไ", e: "ำ", r: "พ", t: "ะ", y: "ั", u: "ี", i: "ร", o: "น", p: "ย", "[": "บ", "]": "ล", "\\": "ฃ",
  a: "ฟ", s: "ห", d: "ก", f: "ด", g: "เ", h: "้", j: "่", k: "า", l: "ส", ";": "ว", "'": "ง",
  z: "ผ", x: "ป", c: "แ", v: "อ", b: "ิ", n: "ื", m: "ท", ",": "ม", ".": "ใ", "/": "ฝ",
  "!": "+", "@": "๑", "#": "๒", $: "๓", "%": "๔", "^": "ู", "&": "฿", "*": "๕", "(": "๖", ")": "๗",
  _: "๘", "+": "๙", "~": "%",
  Q: "๐", W: '"', E: "ฎ", R: "ฑ", T: "ธ", Y: "ํ", U: "๊", I: "ณ", O: "ฯ", P: "ญ", "{": "ฐ", "}": ",", "|": "ฅ",
  A: "ฤ", S: "ฆ", D: "ฏ", F: "โ", G: "ฌ", H: "็", J: "๋", K: "ษ", L: "ศ", ":": "ซ", '"': ".",
  Z: "(", X: ")", C: "ฉ", V: "ฮ", B: "ฺ", N: "์", M: "?", "<": "ฒ", ">": "ฬ", "?": "ฦ",
};

/** ตารางย้อนกลับ: ตัวที่ออกมา → ตัวอังกฤษตัวจริงที่ยิงมา */
const EN_FROM_TH: Record<string, string> = {};
for (const [en, th] of Object.entries(TH_FROM_EN)) EN_FROM_TH[th] = en;

/** มีตัวอักษรไทยปนอยู่ไหม */
export const hasThai = (s: string) => /[฀-๿]/.test(s);

/** แปลงข้อความที่ยิงมาตอนคีย์บอร์ดเป็นไทย ให้กลับเป็นตัวอังกฤษตัวจริง */
export function thaiToEn(s: string) {
  let out = "";
  for (const ch of s) out += EN_FROM_TH[ch] ?? ch;
  return out;
}

/**
 * ตัวจับ "การยิงสแกน"
 * คนพิมพ์เองเร็วสุดราว 10 ตัว/วินาที · เครื่องสแกนยิงเร็วกว่านั้นหลายเท่า
 * ถ้าตัวอักษรไหลเข้ามาติด ๆ กันเกิน BURST_MIN ตัว โดยห่างกันไม่เกิน BURST_GAP มิลลิวินาที
 * ถือว่ามาจากเครื่องสแกน
 */
const BURST_GAP = 45;
const BURST_MIN = 5;

export function makeBurstDetector() {
  let last = 0;
  let run = 0;
  return {
    /** เรียกทุกครั้งที่ช่องกรอกมีตัวอักษรเปลี่ยน — คืนค่าว่าตอนนี้เป็นการยิงสแกนอยู่ไหม */
    feed(len: number, prevLen: number) {
      const now = Date.now();
      const gap = now - last;
      last = now;
      if (len < prevLen) { run = 0; return false; }      // ลบตัวอักษร = คนทำเอง
      if (len - prevLen > 2) { run = BURST_MIN; return true; } // วางทีเดียวทั้งก้อน
      run = gap <= BURST_GAP ? run + 1 : 1;
      return run >= BURST_MIN;
    },
    reset() { last = 0; run = 0; },
  };
}
